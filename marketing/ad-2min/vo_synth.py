"""
Veyra ad 2 — narrator (VO) synthesis + timeline generator.

Synthesizes each narrator line with a neural voice (edge-tts), measures real
durations, lays them on the 80 s timeline with planned gaps, and emits:

  vo2/L01.wav ...      converted 44.1 kHz stereo line audio
  vo2/timings.py       LINES (id, text, t, dur), SCENE times, TOTAL
  vo2/mouth.npy        per-frame (30 fps) mouth-open envelope for lip-sync

If the spoken total would overrun the 80 s target, it retries at a faster rate.
"""
import asyncio
import json
import subprocess
import wave

import numpy as np

import edge_tts

VOICE = "en-US-AndrewNeural"
TOTAL = 80.0
FPS = 30

LINES_TEXT = [
    ("L01", "This is Amara. Freelance brand designer. Brilliant with her clients — and completely drowning in everything around the work."),
    ("L02a", "Leads scattered across five apps."),
    ("L02b", "Follow-ups sent whenever she remembers."),
    ("L02c", "And every proposal? Starting from a blank page."),
    ("L03a", "So she did what everyone does — she subscribed."),
    ("L03b", "HoneyBook. Dubsado. Bonsai. ClickUp."),
    ("L04a", "Helpful? Sure. But that's twenty to eighty dollars a month — every month."),
    ("L04b", "And her clients' data? Sitting on somebody else's cloud."),
    ("L05", "Do the math with me. Forty dollars a month, is two thousand four hundred dollars over five years."),
    ("L06", "Then Amara found Veyra."),
    ("L06b", "Not another subscription. Not another browser tab. A system she downloads — and owns."),
    ("L07a", "It runs on her own computer — so her client data never leaves it."),
    ("L07b", "One payment. Seventy-nine dollars. Hers forever."),
    ("L08a", "Now follow-ups go out on time. Proposals start from a system — not a blank page."),
    ("L08b", "And she can finally see the whole journey — build, acquire, sell, deliver, retain, grow."),
    ("L09", "Amara didn't get more hours. She got a system. Veyra — practical business systems you can actually run."),
]

# minimum gap AFTER each line, in seconds (slack is distributed on top)
MIN_GAP = {
    "L01": 0.8, "L02a": 0.3, "L02b": 0.3, "L02c": 0.8, "L03a": 0.15,
    "L03b": 0.7, "L04a": 0.2, "L04b": 0.7, "L05": 1.2, "L06": 0.3,
    "L06b": 0.3, "L07a": 0.2, "L07b": 0.7, "L08a": 0.2, "L08b": 0.5,
    "L09": 0.0,
}
START_PAD = 0.6          # cold open before the first line
END_CARD = 5.0           # end-card hold after the last line


async def build():
    chosen = None
    for rate in ("+0%", "+5%", "+10%", "+16%"):
        durs = {}
        for lid, text in LINES_TEXT:
            mp3, wav = f"vo2/{lid}.mp3", f"vo2/{lid}.wav"
            await synth(text, mp3, rate)
            to_wav(mp3, wav)
            durs[lid] = wav_dur(wav)
        speech = sum(durs.values())
        layout = START_PAD + speech + sum(MIN_GAP.values()) + END_CARD
        print(f"rate {rate}: speech {speech:.2f}s, layout {layout:.2f}s")
        if layout <= TOTAL:
            chosen = (rate, durs)
            break
    if chosen is None:
        chosen = ("+16%", durs)
    rate, durs = chosen

    slack = TOTAL - (START_PAD + sum(durs.values()) + sum(MIN_GAP.values())
                     + END_CARD)
    n_gaps = sum(1 for lid in MIN_GAP if MIN_GAP[lid] > 0)
    extra = min(slack / n_gaps, 0.9) if n_gaps else 0.0
    tail = TOTAL - (START_PAD + sum(durs.values())
                    + sum(min(g + extra, g + 0.9) for g in MIN_GAP.values()))
    print(f"chosen rate {rate}, extra gap +{extra:.2f}s, tail {tail:.2f}s")

    placed = []
    t = START_PAD
    for lid, text in LINES_TEXT:
        placed.append((lid, text, t, durs[lid]))
        t += durs[lid] + min(MIN_GAP[lid] + extra, MIN_GAP[lid] + 0.9)

    # mouth envelope on the global 80 s grid
    nf = int(TOTAL * FPS) + 1
    mouth = np.zeros(nf)
    for lid, _text, t0, d in placed:
        e, _p = rms_env(f"vo2/{lid}.wav", t0)
        i0 = int(t0 * FPS)
        m = min(len(e), nf - i0)
        mouth[i0:i0 + m] = np.maximum(mouth[i0:i0 + m], e[:m])
    np.save("vo2/mouth.npy", mouth.astype(np.float32))

    # scene boundaries derived from the line layout
    def t_of(lid):
        return next(p[2] for p in placed if p[0] == lid)

    scenes = {
        "S1_hook":    0.0,
        "S2_problem": t_of("L02a") - 0.25,
        "S3_subs":    t_of("L03a") - 0.30,
        "S4_math":    t_of("L05") - 0.35,
        "S5_switch":  t_of("L06") - 0.30,
        "S6_wins":    t_of("L08a") - 0.30,
        "S7_cta":     t_of("L09") - 0.35,
    }

    with open("vo2/timings.py", "w", encoding="utf-8") as f:
        f.write("# AUTOGENERATED by vo_synth.py — do not edit by hand\n")
        f.write(f"TOTAL = {TOTAL}\nVOICE = {VOICE!r}\n")
        f.write("LINES = " + json.dumps(
            [(lid, t, d) for lid, _x, t, d in placed]) + "\n")
        f.write("SCENES = " + json.dumps(scenes) + "\n")
    print("scenes:", {k: round(v, 2) for k, v in scenes.items()})
    print("wrote vo2/timings.py, vo2/mouth.npy")


async def synth(text, path, rate):
    c = edge_tts.Communicate(text, VOICE, rate=rate)
    await c.save(path)


def to_wav(mp3, wav):
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", mp3,
                    "-ar", "44100", "-ac", "2", wav], check=True)


def wav_dur(path):
    with wave.open(path, "rb") as w:
        return w.getnframes() / w.getframerate()


def rms_env(path, t0):
    """Per-30fps-frame smoothed RMS of a line, placed on the global grid."""
    with wave.open(path, "rb") as w:
        sr = w.getframerate()
        n = w.getnframes()
        x = np.frombuffer(w.readframes(n), dtype=np.int16).astype(np.float64)
        x = x.reshape(-1, 2).mean(axis=1) / 32768.0
    hop = sr / FPS
    nf = int(n / hop) + 1
    idx = (np.arange(nf - 1) * hop).astype(int)
    win = int(0.03 * sr)
    cs = np.concatenate([[0.0], np.cumsum(x ** 2)])
    e = np.sqrt((cs[idx + win] - cs[idx]) / win)
    if len(e) < 2:
        return np.zeros(0), 1.0
    k = np.exp(-np.linspace(-2, 2, 7) ** 2)
    e = np.convolve(e, k / k.sum(), mode="same")
    peak = e.max() + 1e-9
    e = np.clip(e / peak, 0, 1) ** 0.55
    return e, peak


if __name__ == "__main__":
    asyncio.run(build())
